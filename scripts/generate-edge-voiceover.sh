#!/usr/bin/env bash
set -euo pipefail
mkdir -p edge-audio

lines=(
  "Представь город, где зрение считают опасной болезнью."
  "Все ходят с закрытыми глазами. Смотреть запрещено законом."
  "Но однажды один человек впервые видит свет."
  "На стенах он замечает послания тех, кто проснулся раньше."
  "Каждую ночь улицы меняются. А окна домов следят за людьми."
  "И тогда он понимает: слепота была не наказанием. Она защищала их."
  "Потому что, когда ты смотришь в бездну, бездна запоминает твоё лицо."
  "А ты бы открыл глаза? Город слепых. Продолжение следует."
)

for i in "${!lines[@]}"; do
  n=$(printf '%02d' "$((i + 1))")
  edge-tts \
    --voice ru-RU-DmitryNeural \
    --rate=+18% \
    --pitch=-4Hz \
    --text "${lines[$i]}" \
    --write-media "edge-audio/voice-${n}.mp3"
done
